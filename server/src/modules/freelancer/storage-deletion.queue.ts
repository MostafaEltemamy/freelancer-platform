import { randomUUID } from 'node:crypto';
import { prisma } from '../../database/prisma.js';
import type {Prisma} from '../../generated/prisma/client.js';
import {deleteStoredObject, storedObjectExists} from './project-media.storage.js';

// ---------------------------------------------------------
// Cleanup policy
// ---------------------------------------------------------

// Signed uploads last two minutes. Finalization can begin
// later and can involve storage/network processing.
//
// Delay cleanup of young records so an in-flight upload
// cannot recreate an object immediately after deletion.
//
// This is a safety grace period, not an exact guarantee
// against an indefinitely stalled external operation.
const MEDIA_CLEANUP_GRACE_MS = 30 * 60_000;
const LEASE_MS = 5 * 60_000;
const WORKER_INTERVAL_MS = 60_000;
const MAX_BATCH_SIZE = 20;
const MAX_RETRY_DELAY_MS = 60 * 60_000;
// R2 DELETE is followed by two delayed HEAD checks.
const FIRST_VERIFICATION_DELAY_MS = 5 * 60_000;
const FINAL_VERIFICATION_DELAY_MS = 30 * 60_000;

class ReferencedStorageKeyError extends Error {
  constructor() {
    super('Object key is still referenced by media.');
    this.name = 'ReferencedStorageKeyError';
  }
}

// Only keys generated by our media-key conventions may
// enter this queue. Client-provided keys are forbidden.
const MANAGED_OBJECT_KEY =
  /^projects\/[0-9a-f-]{36}\/(?:previews\/)?[0-9a-f-]{36}\.(?:jpg|jpeg|png|webp|mp4|webm|pdf)$/i;

export interface MediaCleanupSource {
  storageKey: string;
  previewKey: string | null;
  createdAt: Date;
}

// ---------------------------------------------------------
// Enqueue inside the caller's existing DB transaction
// ---------------------------------------------------------

export async function enqueueMediaObjectCleanup(
  tx: Prisma.TransactionClient,
  media: readonly MediaCleanupSource[],
  options: {
    notBefore?: Date;
  } = {},
): Promise<void> {
  const now = Date.now();

  const jobs: Array<{
    objectKey: string;
    nextAttemptAt: Date;
  }> = [];

  for (const item of media) {
    const nextAttemptAt = new Date(
      Math.max(
        now,
        item.createdAt.getTime() +
          MEDIA_CLEANUP_GRACE_MS,
        options.notBefore?.getTime() ?? 0,
      ),
    );

    const objectKeys = [
      item.storageKey,
      item.previewKey,
    ].filter(
      (key): key is string =>
        typeof key === 'string',
    );

    for (const objectKey of objectKeys) {
      if (!MANAGED_OBJECT_KEY.test(objectKey)) {
        // Fail closed. Never delete an arbitrary key.
        throw new Error(
          'A media object has an invalid storage key.',
        );
      }

      jobs.push({
        objectKey,
        nextAttemptAt,
      });
    }
  }

  if (jobs.length === 0) {
    return;
  }

  await tx.storageDeletionJob.createMany({
    data: jobs,
    skipDuplicates: true,
  });
}

// ---------------------------------------------------------
// Retry timing
// ---------------------------------------------------------

function retryDelayMs(failures: number): number {
  return Math.min(
    MAX_RETRY_DELAY_MS,
    1_000 * 2 ** Math.min(failures, 12),
  );
}

// ---------------------------------------------------------
// Process one bounded batch
// ---------------------------------------------------------

export async function processStorageDeletionBatch(
  maxItems = MAX_BATCH_SIZE,
  options: {
    onlyJobId?: string;

    // Injectable for deterministic tests.
    removeObject?: (key: string) => Promise<void>;
    objectExists?: (key: string) => Promise<boolean>;
  } = {},
): Promise<{
  claimed: number;
  deleted: number;
  failed: number;
}> {
  if (
    !Number.isInteger(maxItems) ||
    maxItems < 1 ||
    maxItems > MAX_BATCH_SIZE
  ) {
    throw new RangeError('Invalid cleanup batch size.');
  }

  const now = new Date();

  const dueJobs = await prisma.storageDeletionJob.findMany({
    where: {
      ...(options.onlyJobId
        ? { id: options.onlyJobId }
        : {}),

      nextAttemptAt: {
        lte: now,
      },

      OR: [
        { leaseUntil: null },
        { leaseUntil: { lte: now } },
      ],
    },

    select: {
      id: true,
      objectKey: true,
      nextAttemptAt: true,
      phase: true,
      verificationPasses: true,
      consecutiveFailures: true,
    },

    orderBy: [
      { nextAttemptAt: 'asc' },
      { createdAt: 'asc' },
    ],

    take: maxItems,
  });

  let claimed = 0;
  let deleted = 0;
  let failed = 0;

  for (const job of dueJobs) {
    const claimTime = new Date();
    const token = randomUUID();

    // Exact phase + timestamp conditions prevent stale
    // workers from claiming an already transitioned job.
    const claim =
      await prisma.storageDeletionJob.updateMany({
        where: {
          id: job.id,
          phase: job.phase,
          verificationPasses: job.verificationPasses,
          nextAttemptAt: job.nextAttemptAt,

          OR: [
            { leaseUntil: null },
            { leaseUntil: { lte: claimTime } },
          ],
        },

        data: {
          leaseToken: token,
          leaseUntil: new Date(
            claimTime.getTime() + LEASE_MS,
          ),
          attempts: { increment: 1 },
        },
      });

    if (claim.count !== 1) {
      continue;
    }

    claimed++;

    try {
      if (!MANAGED_OBJECT_KEY.test(job.objectKey)) {
        throw new Error('Invalid managed storage key.');
      }

      // Fail closed if metadata once again references
      // this key. Never intentionally remove an object
      // currently associated with a live media record.
      const referenced =
        await prisma.projectMedia.findFirst({
          where: {
            OR: [
              { storageKey: job.objectKey },
              { previewKey: job.objectKey },
            ],
          },
          select: { id: true },
        });

      if (referenced) {
        throw new ReferencedStorageKeyError();
      }

      if (job.phase === 'DELETE') {
        // -------------------------------------------------
        // Phase 1: remove object
        // -------------------------------------------------

        await (
          options.removeObject ?? deleteStoredObject
        )(job.objectKey);

        // The DELETE succeeded, but retain the job.
        // First verification occurs after five minutes.
        const result =
          await prisma.storageDeletionJob.updateMany({
            where: {
              id: job.id,
              leaseToken: token,
              phase: 'DELETE',
            },

            data: {
              phase: 'VERIFY',
              verificationPasses: 0,
              nextAttemptAt: new Date(
                Date.now() +
                FIRST_VERIFICATION_DELAY_MS,
              ),
              leaseToken: null,
              leaseUntil: null,
              consecutiveFailures: 0,
              lastError: null,
            },
          });

        if (result.count === 1) {
          deleted++;
        }

        continue;
      }

      // ---------------------------------------------------
      // Phase 2: check whether object exists
      // ---------------------------------------------------

      if (
        job.verificationPasses !== 0 &&
        job.verificationPasses !== 1
      ) {
        throw new Error(
          'Invalid cleanup verification state.',
        );
      }

      const exists = await (
        options.objectExists ?? storedObjectExists
      )(job.objectKey);

      if (exists) {
        // A delayed PUT or another write recreated the
        // object. Return the job to DELETE.
        //
        // The next worker tick performs removal again.
        await prisma.storageDeletionJob.updateMany({
          where: {
            id: job.id,
            leaseToken: token,
            phase: 'VERIFY',
          },

          data: {
            phase: 'DELETE',
            verificationPasses: 0,
            nextAttemptAt: new Date(),
            leaseToken: null,
            leaseUntil: null,
            consecutiveFailures: 0,
            lastError: null,
          },
        });

        continue;
      }

      if (job.verificationPasses === 0) {
        // First check passed. Keep the job for a
        // second check thirty minutes later.
        await prisma.storageDeletionJob.updateMany({
          where: {
            id: job.id,
            leaseToken: token,
            phase: 'VERIFY',
            verificationPasses: 0,
          },

          data: {
            verificationPasses: 1,
            nextAttemptAt: new Date(
              Date.now() +
              FINAL_VERIFICATION_DELAY_MS,
            ),
            leaseToken: null,
            leaseUntil: null,
            consecutiveFailures: 0,
            lastError: null,
          },
        });

        continue;
      }

      // ---------------------------------------------------
      // Final verification succeeded
      // ---------------------------------------------------

      // This job is now eligible to be removed.
      // The lease check prevents deletion of a job
      // reassigned to another worker.
      await prisma.storageDeletionJob.deleteMany({
        where: {
          id: job.id,
          leaseToken: token,
          phase: 'VERIFY',
          verificationPasses: 1,
        },
      });
    } catch (error) {
      failed++;

      const category =
        error instanceof Error
          ? error.name.slice(0, 120)
          : 'UnknownStorageError';

      await prisma.storageDeletionJob.updateMany({
        where: {
          id: job.id,
          leaseToken: token,
        },

        data: {
          leaseToken: null,
          leaseUntil: null,

          nextAttemptAt: new Date(
            Date.now() +
            retryDelayMs(
              job.consecutiveFailures + 1,
            ),
          ),

          consecutiveFailures: {
            increment: 1,
          },

          lastError: category,
        },
      });
    }
  }

  return {
    claimed,
    deleted,
    failed,
  };
}

// ---------------------------------------------------------
// Background worker lifecycle
// ---------------------------------------------------------

export function startStorageDeletionWorker():
  () => Promise<void> {
  if (!process.env.S3_BUCKET) {
    console.warn(
      'Storage cleanup worker disabled: S3_BUCKET is missing.',
    );

    return async () => {};
  }

  let stopped = false;
  let active: Promise<void> | null = null;

  function tick(): void {
    if (stopped || active) {
      return;
    }

    active = (async () => {
      try {
        const result =
          await processStorageDeletionBatch();

        if (result.failed > 0) {
          console.warn(
            'Some storage cleanup operations failed; ' +
            'they have been scheduled for retry.',
            {
              failures: result.failed,
            },
          );
        }
      } catch (error) {
        // Log categories only. The next tick will retry.
        console.error(
          'Storage cleanup worker error:',
          error instanceof Error
            ? error.name
            : 'UnknownError',
        );
      }
    })().finally(() => {
      active = null;
    });
  }

  const timer = setInterval(
    tick,
    WORKER_INTERVAL_MS,
  );

  timer.unref();

  // Check for older queued work on startup.
  tick();

  return async () => {
    stopped = true;
    clearInterval(timer);

    // Allow a running batch to finish during
    // graceful server shutdown.
    await active;
  };
}
